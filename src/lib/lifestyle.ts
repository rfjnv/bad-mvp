export interface Recommendation {
  categorySlug: string;
  /** Условия, из-за которых категория попала в подборку */
  reasons: string[];
}

/**
 * Собирает рекомендации по выбранным условиям.
 * Категории идут по числу совпавших условий: то, что подтверждается
 * сразу несколькими ответами, важнее того, что вылезло из одного.
 */
export function recommendFor(selectedSlugs: string[]): Recommendation[] {
  const selected = CONDITIONS.filter((c) => selectedSlugs.includes(c.slug));
  const byCategory = new Map<string, string[]>();

  for (const condition of selected) {
    for (const categorySlug of condition.categorySlugs) {
      const existing = byCategory.get(categorySlug) ?? [];
      existing.push(condition.reason);
      byCategory.set(categorySlug, existing);
    }
  }

  return [...byCategory.entries()]
    .map(([categorySlug, reasons]) => ({ categorySlug, reasons }))
    .sort((a, b) => b.reasons.length - a.reasons.length);
}
